static const UINT8* GetGlyph(char c) {
    if (c == ' ') return font8x8[0];
    if (c >= '0' && c <= '9') return font8x8[1 + (c - '0')];
    if (c == ':') return colonGlyph;
    if (c == '.') return periodGlyph;
    if (c == '!') return exclaimGlyph;
    if (c == '_') return underscoreGlyph;
    if (c == '-') return minusGlyph;
    if (c == '+') return plusGlyph;
    if (c == '=') return equalsGlyph;
    if (c == '(') return lparenGlyph;
    if (c == ')') return rparenGlyph;
    if (c == '[') return lbracketGlyph;
    if (c == ']') return rbracketGlyph;
    if (c == '/') return slashGlyph;
    if (c == '{') return lbraceGlyph;
    if (c == '}') return rbraceGlyph;
    if (c == '&') return ampersandGlyph;
    if (c == '\x03') return glyphO_uml;  // Ö
    if (c == '\x02') return glyphA_uml;  // Ä
    if (c == '\x01') return glyphA_ring; // Å
    for (const auto &g : letterFont) {
        if (g.c == c) return g.rows;
    }
    return font8x8[0];
}




void Text::DrawChar(UINT32 *framebuffer, UINT32 stride, UINT32 x, UINT32 y, char c, UINT32 color) {
    const UINT8 *glyph = GetGlyph(c);
    for (UINT32 row = 0; row < 8; row++) {
        UINT8 bits = glyph[row];
        for (UINT32 col = 0; col < 8; col++) {
            if (bits & (0x80 >> col)) {
                framebuffer[(y + row) * stride + (x + col)] = color;
            }
        }
    }
}

void Text::DrawString(UINT32 *framebuffer, UINT32 stride, UINT32 x, UINT32 y, const char *str, UINT32 color) {
    UINT32 cursorX = x;
    while (*str) {
        DrawChar(framebuffer, stride, cursorX, y, *str, color);
        cursorX += 9; 
        str++;
    }
}