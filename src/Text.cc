void Text::UInt64ToStr(UINT64 value, CHAR16 *buffer) {
    CHAR16 temp[21];
    int i = 0;

    if (value == 0) {
        buffer[0] = L'0';
        buffer[1] = L'\0';
        return;
    }

    while (value > 0) {
        temp[i++] = L'0' + (value % 10);
        value /= 10;
    }

    int j = 0;

    while (i > 0) {
        buffer[j++] = temp[--i];
    }
    buffer[j] = L'\0';
}


