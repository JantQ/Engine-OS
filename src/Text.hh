static const UINT8* GetGlyph(char c) {
    if (c == ' ') return font8x8[0];
    if (c >= '0' && c <= '9') return font8x8[1 + (c - '0')];
    if (c == ':') return colon;
    if (c == '.') return period;
    if (c == '!') return exclaim;
    if (c == '_') return underscore;
    if (c == '-') return minusGlyph;
    if (c == '+') return plusGlyph;
    if (c == '=') return equalsGlyph;
    if (c == '(') return lparenGlyph;
    if (c == ')') return rparenGlyph;
    if (c == '[') return lbracketGlyph;
    if (c == ']') return rbracketGlyph;
    if (c == '/') return slashGlyph;
    if (c == '{') return lbrace;
    if (c == '}') return rbrace;
    if (c == '&') return ampersand;
    if (c == '\\') return backSlash;
    if (c == '|') return pipe;
    if (c == '`') return backTick;
    if (c == '\x01') return glyphA_ring; // Å
    if (c == '\x02') return glyphA_uml;  // Ä
    if (c == '\x03') return glyphO_uml;  // Ö
    if (c == '\x04') return backSlash; // '\'
    if (c == '\x05') return pipe; // |
    if (c == ',') return comma;
    if (c == '\'') return apostrophe;
    if (c == '?') return questionMark;
    if (c == '"')  return quoteGlyph;
    if (c == '#')  return hashGlyph;
    if (c == '%')  return percentGlyph;
    if (c == ';')  return semicolon;
    if (c == '*')  return asterisk;
    if (c == '@')  return atGlyph;
    if (c == '$')  return dollarGlyph;
    if (c == '~')  return tildeGlyph;
    if (c == '<')  return lessThan;
    if (c == '>')  return greaterThan;

    for (const auto &g : letterFont) {
        if (g.c == c) return g.rows;
    }
    return font8x8[0];
}

